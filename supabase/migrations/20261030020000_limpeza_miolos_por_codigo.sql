-- Canonicaliza miolos de agendas/cadernos pelo token inicial do SKU.
-- Kits, SKUs malformados e produtos sem BOM sao apenas auditados.

BEGIN;

CREATE TABLE IF NOT EXISTS public.miolo_codigo_limpeza_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL,
  action text NOT NULL,
  codigo text,
  produto_id integer,
  miolo_origem_id integer,
  miolo_canonico_id integer,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TEMP TABLE _miolo_product_codes ON COMMIT DROP AS
SELECT p.id AS produto_id,
       split_part(btrim(p.sku), '_', 1) AS codigo,
       p.sku,
       p.formato,
       p.categoria_id,
       CASE
         WHEN p.formato = 'kit' THEN 'kit'
         WHEN p.sku ~ '^[A-Z0-9]{4,6}(_|$)'
              AND length(split_part(btrim(p.sku), '_', 1)) IN (4, 6)
           THEN 'elegivel'
         ELSE 'sku_invalido'
       END AS classificacao
FROM public.produtos p
WHERE p.categoria_id IN (7, 11);

CREATE TEMP TABLE _miolo_code_canonicals ON COMMIT DROP AS
WITH eligible AS (
  SELECT DISTINCT produto_id, codigo
  FROM _miolo_product_codes
  WHERE classificacao = 'elegivel'
), bom_codes AS (
  SELECT e.codigo,
         min(ft.componente_id) AS primeiro_componente
  FROM eligible e
  JOIN public.ficha_tecnica ft ON ft.produto_pai_id = e.produto_id
  JOIN public.produtos component ON component.id = ft.componente_id
                               AND component.categoria_id = 6
  GROUP BY e.codigo
), existing AS (
  SELECT replace(sku, 'MIOLO-', '') AS codigo, min(id) AS id
  FROM public.produtos
  WHERE categoria_id = 6
    AND sku IN (SELECT 'MIOLO-' || codigo FROM bom_codes)
  GROUP BY codigo
)
SELECT b.codigo,
       coalesce(x.id, b.primeiro_componente) AS canonical_id
FROM bom_codes b
LEFT JOIN existing x ON x.codigo = b.codigo;

CREATE TEMP TABLE _miolo_component_map ON COMMIT DROP AS
SELECT DISTINCT component.id AS source_id,
       c.codigo,
       c.canonical_id
FROM _miolo_code_canonicals c
JOIN _miolo_product_codes pc ON pc.codigo = c.codigo
                           AND pc.classificacao = 'elegivel'
JOIN public.ficha_tecnica ft ON ft.produto_pai_id = pc.produto_id
JOIN public.produtos component ON component.id = ft.componente_id
                              AND component.categoria_id = 6;

CREATE INDEX _miolo_component_map_source_idx ON _miolo_component_map(source_id);
CREATE INDEX _miolo_component_map_canonical_idx ON _miolo_component_map(canonical_id);

DO $$
DECLARE
  v_run uuid := gen_random_uuid();
  v_row record;
  v_fk record;
  v_has_rows boolean;
  v_pending_ficha_id integer;
BEGIN
  INSERT INTO public.miolo_codigo_limpeza_log
    (run_id, action, codigo, produto_id, details)
  SELECT v_run, 'produto_elegivel', codigo, produto_id,
         jsonb_build_object('sku', sku, 'formato', formato, 'categoria_id', categoria_id)
  FROM _miolo_product_codes
  WHERE classificacao = 'elegivel';

  INSERT INTO public.miolo_codigo_limpeza_log
    (run_id, action, codigo, produto_id, details)
  SELECT v_run, classificacao, codigo, produto_id,
         jsonb_build_object('sku', sku, 'formato', formato, 'categoria_id', categoria_id)
  FROM _miolo_product_codes
  WHERE classificacao <> 'elegivel';

  INSERT INTO public.miolo_codigo_limpeza_log
    (run_id, action, codigo, miolo_origem_id, miolo_canonico_id)
  SELECT v_run, 'miolo_mapeado', codigo, source_id, canonical_id
  FROM _miolo_component_map;

  -- Uma linha por produto/codigo; a regra do SKU prevalece sobre a BOM antiga.
  FOR v_row IN
    SELECT c.codigo, pc.produto_id,
           c.canonical_id,
           coalesce(sum(ft.quantidade_necessaria), 0) AS quantidade_total,
           coalesce(min(ft.id) FILTER (WHERE ft.componente_id = c.canonical_id), min(ft.id)) AS keep_id
    FROM _miolo_code_canonicals c
    JOIN _miolo_product_codes pc ON pc.codigo = c.codigo AND pc.classificacao = 'elegivel'
    JOIN public.ficha_tecnica ft ON ft.produto_pai_id = pc.produto_id
    JOIN public.produtos component ON component.id = ft.componente_id AND component.categoria_id = 6
    GROUP BY c.codigo, pc.produto_id, c.canonical_id
  LOOP
    -- Preserva classificacoes pendentes ligadas a linhas BOM que serao mescladas.
    SELECT min(pending.ficha_tecnica_id)
      INTO v_pending_ficha_id
      FROM public.ficha_tecnica_classificacao_pendente pending
     WHERE pending.ficha_tecnica_id IN (
             SELECT id FROM public.ficha_tecnica
              WHERE produto_pai_id = v_row.produto_id
                AND componente_id IN (SELECT source_id FROM _miolo_component_map WHERE codigo = v_row.codigo)
           )
       AND pending.ficha_tecnica_id <> v_row.keep_id;

    IF v_pending_ficha_id IS NOT NULL
       AND NOT EXISTS (
             SELECT 1 FROM public.ficha_tecnica_classificacao_pendente keep_pending
              WHERE keep_pending.ficha_tecnica_id = v_row.keep_id
           ) THEN
      UPDATE public.ficha_tecnica_classificacao_pendente
         SET ficha_tecnica_id = v_row.keep_id
       WHERE ficha_tecnica_id = v_pending_ficha_id;
    END IF;

    UPDATE public.ficha_tecnica
       SET componente_id = v_row.canonical_id,
           quantidade_necessaria = v_row.quantidade_total,
           sku_componente = 'MIOLO-' || v_row.codigo,
           updated_at = now()
     WHERE id = v_row.keep_id;

    DELETE FROM public.ficha_tecnica_classificacao_pendente pending
     WHERE pending.ficha_tecnica_id IN (
             SELECT id FROM public.ficha_tecnica
              WHERE produto_pai_id = v_row.produto_id
                AND componente_id IN (SELECT source_id FROM _miolo_component_map WHERE codigo = v_row.codigo)
           )
       AND pending.ficha_tecnica_id <> v_row.keep_id;

    DELETE FROM public.ficha_tecnica
     WHERE produto_pai_id = v_row.produto_id
       AND componente_id IN (SELECT source_id FROM _miolo_component_map WHERE codigo = v_row.codigo)
       AND id <> v_row.keep_id;
  END LOOP;

  -- Redireciona FKs para os miolos antigos, exceto ficha_tecnica, tratada acima.
  FOR v_fk IN
    SELECT ns.nspname AS schema_name,
           nt.relname AS table_name,
           a.attname AS column_name
    FROM pg_constraint c
    JOIN pg_class nt ON nt.oid = c.conrelid
    JOIN pg_namespace ns ON ns.oid = nt.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
    WHERE c.contype = 'f'
      AND c.confrelid = 'public.produtos'::regclass
      AND cardinality(c.conkey) = 1
      AND cardinality(c.confkey) = 1
      AND NOT (ns.nspname = 'public' AND nt.relname = 'ficha_tecnica')
  LOOP
    EXECUTE format(
      'SELECT EXISTS (SELECT 1 FROM %I.%I target
        JOIN _miolo_component_map map ON target.%I = map.source_id
       WHERE map.source_id <> map.canonical_id)',
      v_fk.schema_name, v_fk.table_name, v_fk.column_name
    ) INTO v_has_rows;
    IF v_has_rows THEN
      EXECUTE format(
        'UPDATE %I.%I target SET %I = map.canonical_id
          FROM _miolo_component_map map
         WHERE target.%I = map.source_id
           AND map.source_id <> map.canonical_id',
        v_fk.schema_name, v_fk.table_name, v_fk.column_name, v_fk.column_name
      );
    END IF;
  END LOOP;

  UPDATE public.produtos canonical
     SET nome = 'Miolo ' || map.codigo,
         sku = 'MIOLO-' || map.codigo,
         categoria_id = 6,
         tipo_material = 'intermediario',
         updated_at = now()
    FROM (SELECT DISTINCT codigo, canonical_id FROM _miolo_component_map) map
   WHERE canonical.id = map.canonical_id;

  -- Remove duplicatas somente quando nao houver nenhuma FK restante.
  FOR v_row IN
    SELECT DISTINCT source_id, canonical_id, codigo
    FROM _miolo_component_map
    WHERE source_id <> canonical_id
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM public.ficha_tecnica WHERE componente_id = v_row.source_id
    ) AND NOT EXISTS (
      SELECT 1 FROM public.itens_demanda WHERE id_produto_miolo = v_row.source_id
    ) AND NOT EXISTS (
      SELECT 1 FROM public.estoque_atual WHERE produto_id = v_row.source_id
    ) AND NOT EXISTS (
      SELECT 1 FROM public.movimentacoes_estoque WHERE produto_id = v_row.source_id
    ) THEN
      DELETE FROM public.produtos WHERE id = v_row.source_id;
      INSERT INTO public.miolo_codigo_limpeza_log
        (run_id, action, codigo, miolo_origem_id, miolo_canonico_id)
      VALUES (v_run, 'miolo_removido', v_row.codigo, v_row.source_id, v_row.canonical_id);
    ELSE
      INSERT INTO public.miolo_codigo_limpeza_log
        (run_id, action, codigo, miolo_origem_id, miolo_canonico_id, details)
      VALUES (v_run, 'miolo_preservado_com_referencia', v_row.codigo,
              v_row.source_id, v_row.canonical_id,
              jsonb_build_object('motivo', 'referencia_remanescente'));
    END IF;
  END LOOP;
END $$;

UPDATE public.itens_demanda i
   SET miolo_nome = btrim(i.miolo_chave)
 WHERE nullif(btrim(i.miolo_chave), '') IS NOT NULL
   AND i.miolo_nome IS DISTINCT FROM btrim(i.miolo_chave);

COMMIT;
