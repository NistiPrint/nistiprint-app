-- Intenção e transições auditáveis para solicitações de impressão.
ALTER TABLE public.impressao_capas_envios
    ADD COLUMN IF NOT EXISTS content_hash text,
    ADD COLUMN IF NOT EXISTS agent_id text,
    ADD COLUMN IF NOT EXISTS retry_of uuid REFERENCES public.impressao_capas_envios(request_id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

CREATE TABLE IF NOT EXISTS public.impressao_capas_envios_eventos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL REFERENCES public.impressao_capas_envios(request_id) ON DELETE RESTRICT,
    estado_anterior text,
    estado_novo text NOT NULL,
    mensagem text,
    ator text,
    criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_impressao_envios_eventos_request
    ON public.impressao_capas_envios_eventos(request_id, criado_em);
ALTER TABLE public.impressao_capas_envios_eventos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.impressao_capas_envios_eventos FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.impressao_capas_envios_eventos TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.impressao_capas_envios_eventos_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.criar_intencao_impressao(
    p_request_id uuid, p_plano_id uuid, p_chave_grupo text, p_sku_capa text,
    p_arte_id uuid, p_tipo text, p_quantidade integer, p_printer_name text,
    p_content_hash text, p_ator text, p_retry_of uuid DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_row public.impressao_capas_envios%ROWTYPE;
BEGIN
    IF p_request_id IS NULL OR p_plano_id IS NULL OR p_tipo NOT IN ('estatica','abrir_editor')
       OR p_quantidade < 0 OR p_content_hash !~ '^[0-9a-f]{64}$' THEN
        RAISE EXCEPTION 'Intenção de impressão inválida' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.impressao_capas_envios(
        plano_id,request_id,chave_grupo,sku_capa,arte_id,tipo,quantidade,
        printer_name,status,mensagem,enviado_por,content_hash,retry_of
    ) VALUES (
        p_plano_id,p_request_id,p_chave_grupo,p_sku_capa,p_arte_id,p_tipo,p_quantidade,
        p_printer_name,'PREPARADO',NULL,p_ator,p_content_hash,p_retry_of
    ) ON CONFLICT (request_id) DO NOTHING;
    SELECT * INTO v_row FROM public.impressao_capas_envios WHERE request_id=p_request_id FOR UPDATE;
    IF v_row.plano_id IS DISTINCT FROM p_plano_id OR v_row.content_hash IS DISTINCT FROM p_content_hash THEN
        RAISE EXCEPTION 'request_id reutilizado com conteúdo diferente' USING ERRCODE = '23505';
    END IF;
    IF v_row.status = 'PREPARADO' AND v_row.created_at >= now() - interval '1 second'
       AND NOT EXISTS (SELECT 1 FROM public.impressao_capas_envios_eventos e WHERE e.request_id=p_request_id) THEN
        INSERT INTO public.impressao_capas_envios_eventos(request_id,estado_anterior,estado_novo,ator)
        VALUES (p_request_id,NULL,'PREPARADO',p_ator);
    END IF;
    RETURN to_jsonb(v_row);
END; $$;

CREATE OR REPLACE FUNCTION public.transicionar_intencao_impressao(
    p_request_id uuid, p_estado text, p_mensagem text DEFAULT NULL,
    p_agent_job_id integer DEFAULT NULL, p_printer_name text DEFAULT NULL,
    p_agent_id text DEFAULT NULL, p_ator text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_row public.impressao_capas_envios%ROWTYPE; v_old text;
BEGIN
    IF p_estado NOT IN ('PREPARADO','ENVIANDO','ENVIADO_SPOOLER','CANCELADO','FALHOU',
                        'RESULTADO_DESCONHECIDO','CONFIRMADO_OPERADOR','queued','na_fila',
                        'preparando','imprimindo','enviado','impresso','saiu_da_fila',
                        'sem_rastreio','erro','file_opened') THEN
        RAISE EXCEPTION 'Estado de impressão inválido' USING ERRCODE='22023';
    END IF;
    SELECT * INTO v_row FROM public.impressao_capas_envios WHERE request_id=p_request_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Intenção de impressão não encontrada' USING ERRCODE='P0002'; END IF;
    v_old := v_row.status;
    IF v_old IN ('CANCELADO','FALHOU','RESULTADO_DESCONHECIDO','CONFIRMADO_OPERADOR')
       AND p_estado NOT IN (v_old,'CONFIRMADO_OPERADOR') THEN
        RAISE EXCEPTION 'Transição não permitida: % -> %',v_old,p_estado USING ERRCODE='23514';
    END IF;
    UPDATE public.impressao_capas_envios SET status=p_estado,
        mensagem=p_mensagem, agent_job_id=coalesce(p_agent_job_id,agent_job_id),
        printer_name=coalesce(p_printer_name,printer_name), agent_id=coalesce(p_agent_id,agent_id),
        updated_at=now()
    WHERE request_id=p_request_id RETURNING * INTO v_row;
    IF v_old IS DISTINCT FROM p_estado OR p_mensagem IS NOT NULL OR p_agent_job_id IS NOT NULL THEN
        INSERT INTO public.impressao_capas_envios_eventos(request_id,estado_anterior,estado_novo,mensagem,ator)
        VALUES (p_request_id,v_old,p_estado,p_mensagem,p_ator);
    END IF;
    RETURN to_jsonb(v_row);
END; $$;

