-- Existing hashes point at the last completed extraction. The last-buyer-message
-- timestamp remains the signal that a newer context must be processed.
UPDATE public.mercadolivre_chat_conversations
   SET current_context_hash = context_hash
 WHERE current_context_hash IS NULL AND context_hash IS NOT NULL;

INSERT INTO public.mercadolivre_personalization_batch_items
  (batch_id, marketplace_integration_id, pack_id)
SELECT b.id, b.marketplace_integration_id, item.pack_id
  FROM public.mercadolivre_personalization_batches AS b
 CROSS JOIN LATERAL jsonb_array_elements_text(COALESCE(b.pack_ids, '[]'::jsonb)) AS item(pack_id)
 WHERE b.status NOT IN ('COMPLETED', 'FAILED')
ON CONFLICT (batch_id, pack_id) DO NOTHING;
