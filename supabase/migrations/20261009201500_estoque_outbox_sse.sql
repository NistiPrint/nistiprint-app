-- Durable, post-commit invalidation events for confirmed stock operations.
CREATE TABLE IF NOT EXISTS public.estoque_eventos_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id uuid NOT NULL REFERENCES public.estoque_operacoes(operation_id) ON DELETE RESTRICT,
    event_type text NOT NULL DEFAULT 'estoque.operation.confirmed',
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    available_at timestamptz NOT NULL DEFAULT now(),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_owner text,
    lease_token uuid,
    lease_expires_at timestamptz,
    delivered_at timestamptz,
    last_error text,
    CONSTRAINT uq_estoque_eventos_outbox_operation UNIQUE (operation_id),
    CONSTRAINT estoque_eventos_outbox_lease_consistency CHECK (
        (lease_owner IS NULL AND lease_token IS NULL AND lease_expires_at IS NULL)
        OR (lease_owner IS NOT NULL AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_estoque_eventos_outbox_pending
    ON public.estoque_eventos_outbox(available_at, id)
    WHERE delivered_at IS NULL;

ALTER TABLE public.estoque_eventos_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.estoque_eventos_outbox FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.estoque_eventos_outbox TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.estoque_eventos_outbox_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.enqueue_confirmed_stock_operation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_entities jsonb;
BEGIN
    IF OLD.status IS DISTINCT FROM 'CONFIRMADO' AND NEW.status = 'CONFIRMADO' THEN
        -- Keep only identifiers that clients need to invalidate affected views.
        v_entities := jsonb_strip_nulls(jsonb_build_object(
            'produto_id', NEW.source -> 'produto_id',
            'deposito_id', NEW.source -> 'deposito_id',
            'demanda_id', NEW.source -> 'demanda_id',
            'item_id', NEW.source -> 'item_id',
            'ordem_producao_id', NEW.source -> 'ordem_producao_id'
        ));

        INSERT INTO public.estoque_eventos_outbox(operation_id, payload)
        VALUES (
            NEW.operation_id,
            jsonb_build_object(
                'operation_id', NEW.operation_id,
                'command_type', NEW.command_type,
                'entities', v_entities,
                'confirmed_at', NEW.confirmed_at,
                'versions', coalesce(NEW.result -> 'versions', '{}'::jsonb)
            )
        )
        ON CONFLICT (operation_id) DO NOTHING;
    END IF;
    RETURN NEW;
END
$function$;

DROP TRIGGER IF EXISTS trg_estoque_operation_outbox ON public.estoque_operacoes;
CREATE TRIGGER trg_estoque_operation_outbox
AFTER UPDATE OF status ON public.estoque_operacoes
FOR EACH ROW EXECUTE FUNCTION public.enqueue_confirmed_stock_operation();

CREATE OR REPLACE FUNCTION public.claim_estoque_eventos_outbox(
    p_worker_id text,
    p_limit integer DEFAULT 50,
    p_lease_seconds integer DEFAULT 60
)
RETURNS SETOF public.estoque_eventos_outbox
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
BEGIN
    IF p_worker_id IS NULL OR length(trim(p_worker_id)) = 0 THEN
        RAISE EXCEPTION 'p_worker_id is required' USING ERRCODE = '22023';
    END IF;

    RETURN QUERY
    WITH candidates AS (
        SELECT id
        FROM public.estoque_eventos_outbox
        WHERE delivered_at IS NULL
          AND available_at <= now()
          AND (lease_expires_at IS NULL OR lease_expires_at <= now())
        ORDER BY id
        FOR UPDATE SKIP LOCKED
        LIMIT greatest(1, least(coalesce(p_limit, 50), 200))
    )
    UPDATE public.estoque_eventos_outbox o
       SET lease_owner = p_worker_id,
           lease_token = gen_random_uuid(),
           lease_expires_at = now() + make_interval(secs => greatest(10, least(coalesce(p_lease_seconds, 60), 600))),
           attempts = attempts + 1
      FROM candidates c
     WHERE o.id = c.id
    RETURNING o.*;
END
$function$;

CREATE OR REPLACE FUNCTION public.finish_estoque_evento_outbox(
    p_event_id bigint,
    p_lease_token uuid,
    p_error text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
BEGIN
    UPDATE public.estoque_eventos_outbox
       SET delivered_at = CASE WHEN p_error IS NULL THEN now() ELSE NULL END,
           available_at = CASE WHEN p_error IS NULL THEN available_at
                               ELSE now() + make_interval(secs => least(300, (2 ^ least(attempts, 8))::integer)) END,
           last_error = CASE WHEN p_error IS NULL THEN NULL ELSE left(p_error, 4000) END,
           lease_owner = NULL,
           lease_token = NULL,
           lease_expires_at = NULL
     WHERE id = p_event_id
       AND lease_token = p_lease_token
       AND delivered_at IS NULL;
    RETURN FOUND;
END
$function$;

REVOKE ALL ON FUNCTION public.enqueue_confirmed_stock_operation() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.claim_estoque_eventos_outbox(text, integer, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.finish_estoque_evento_outbox(bigint, uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_estoque_eventos_outbox(text, integer, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.finish_estoque_evento_outbox(bigint, uuid, text) TO service_role;

-- The existing schedule is stored as JSON text inside jsonb. Preserve every
-- other task setting and register a short polling interval for the outbox.
UPDATE public.configuracoes_aplicacao
SET valor = jsonb_set(
    CASE WHEN jsonb_typeof(valor) = 'string' THEN (valor #>> '{}')::jsonb ELSE valor END,
    '{task_schedules,processar-outbox-estoque}',
    '{"enabled":true,"schedule_seconds":5,"description":"Publica eventos confirmados de estoque aos usuários autorizados","task_name":"tasks.estoque_outbox_tasks.process_estoque_outbox"}'::jsonb,
    true
),
updated_at = now()
WHERE nome = 'celery_task_schedules';

