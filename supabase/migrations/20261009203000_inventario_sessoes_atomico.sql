-- Physical inventory sessions and counts. Finalization and all stock balances
-- are committed together using the stock command RPC and observed balances.
CREATE TABLE IF NOT EXISTS public.sessoes_inventario (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    deposito_id integer NOT NULL REFERENCES public.depositos(id) ON DELETE RESTRICT,
    usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    observacoes text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'ABERTA'
        CHECK (status IN ('ABERTA', 'FINALIZADA')),
    finalizado_por integer REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    resultado jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    data_fim timestamptz
);

CREATE TABLE IF NOT EXISTS public.contagens_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id uuid NOT NULL REFERENCES public.sessoes_inventario(id) ON DELETE RESTRICT,
    produto_id integer NOT NULL REFERENCES public.produtos(id) ON DELETE RESTRICT,
    operation_id uuid UNIQUE
        REFERENCES public.estoque_operacoes(operation_id) DEFERRABLE INITIALLY DEFERRED,
    quantidade_sistema numeric(15,4) NOT NULL,
    quantidade_contada numeric(15,4) CHECK (quantidade_contada IS NULL OR quantidade_contada >= 0),
    justificativa text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_contagem_inventario_sessao_produto UNIQUE (sessao_id, produto_id)
);

CREATE INDEX IF NOT EXISTS ix_sessoes_inventario_deposito_status
    ON public.sessoes_inventario(deposito_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_contagens_inventario_sessao
    ON public.contagens_inventario(sessao_id, produto_id);

ALTER TABLE public.sessoes_inventario ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contagens_inventario ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sessoes_inventario, public.contagens_inventario FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.sessoes_inventario, public.contagens_inventario TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.contagens_inventario_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.abrir_sessao_inventario(
    p_deposito_id integer,
    p_usuario_id integer,
    p_produtos integer[] DEFAULT NULL,
    p_observacoes text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_session public.sessoes_inventario%ROWTYPE;
    v_count integer;
BEGIN
    IF p_deposito_id IS NULL OR p_usuario_id IS NULL THEN
        RAISE EXCEPTION 'Depósito e usuário são obrigatórios.' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.sessoes_inventario(deposito_id, usuario_id, observacoes)
    VALUES (p_deposito_id, p_usuario_id, coalesce(p_observacoes, ''))
    RETURNING * INTO v_session;

    INSERT INTO public.contagens_inventario(sessao_id, produto_id, quantidade_sistema)
    SELECT v_session.id, e.produto_id, e.saldo_atual
      FROM public.estoque_atual e
     WHERE e.deposito_id = p_deposito_id
       AND (coalesce(cardinality(p_produtos), 0) = 0 OR e.produto_id = ANY(p_produtos))
     ORDER BY e.produto_id;
    GET DIAGNOSTICS v_count = ROW_COUNT;

    RETURN jsonb_build_object('sessao_id', v_session.id, 'items_count', v_count, 'status', v_session.status);
END
$function$;

CREATE OR REPLACE FUNCTION public.registrar_contagem_inventario(
    p_sessao_id uuid,
    p_produto_id integer,
    p_quantidade numeric,
    p_justificativa text DEFAULT ''
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_deposito integer;
BEGIN
    IF p_quantidade IS NULL OR p_quantidade < 0 OR p_quantidade = 'NaN'::numeric
       OR p_quantidade = 'Infinity'::numeric OR p_quantidade = '-Infinity'::numeric THEN
        RAISE EXCEPTION 'Quantidade contada inválida.' USING ERRCODE = '22023';
    END IF;

    SELECT deposito_id INTO v_deposito
      FROM public.sessoes_inventario
     WHERE id = p_sessao_id AND status = 'ABERTA'
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sessão inexistente ou encerrada.' USING ERRCODE = '55000';
    END IF;

    UPDATE public.contagens_inventario
       SET quantidade_contada = p_quantidade,
           justificativa = coalesce(p_justificativa, ''),
           updated_at = now()
     WHERE sessao_id = p_sessao_id AND produto_id = p_produto_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Produto não pertence ao snapshot desta sessão.' USING ERRCODE = '22023';
    END IF;
    RETURN true;
END
$function$;

CREATE OR REPLACE FUNCTION public.finalizar_sessao_inventario(
    p_sessao_id uuid,
    p_usuario_id integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_session public.sessoes_inventario%ROWTYPE;
    v_count record;
    v_result jsonb;
    v_applied integer := 0;
    v_hash text;
    v_operation_id uuid;
BEGIN
    SELECT * INTO v_session
      FROM public.sessoes_inventario
     WHERE id = p_sessao_id
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sessão de inventário não encontrada.' USING ERRCODE = 'P0002';
    END IF;
    IF p_usuario_id IS NULL THEN
        RAISE EXCEPTION 'Usuário finalizador é obrigatório.' USING ERRCODE = '22023';
    END IF;
    IF v_session.status = 'FINALIZADA' THEN
        RETURN coalesce(v_session.resultado, jsonb_build_object(
            'status', 'success', 'sessao_id', p_sessao_id, 'ajustes_realizados', 0
        ));
    END IF;

    FOR v_count IN
        SELECT * FROM public.contagens_inventario
         WHERE sessao_id = p_sessao_id AND quantidade_contada IS NOT NULL
         ORDER BY produto_id
         FOR UPDATE
    LOOP
        IF v_count.quantidade_contada IS DISTINCT FROM v_count.quantidade_sistema THEN
            v_operation_id := coalesce(v_count.operation_id, gen_random_uuid());
            UPDATE public.contagens_inventario
               SET operation_id = v_operation_id
             WHERE id = v_count.id AND operation_id IS NULL;
            v_hash := 'inventario:' || p_sessao_id::text || ':' || v_count.produto_id::text
                      || ':' || v_count.quantidade_sistema::text || ':' || v_count.quantidade_contada::text;
            v_result := public.executar_comando_estoque(
                v_operation_id,
                'BALANCO',
                v_hash,
                jsonb_build_object(
                    'tipo', 'INVENTARIO',
                    'sessao_id', p_sessao_id,
                    'produto_id', v_count.produto_id,
                    'deposito_id', v_session.deposito_id
                ),
                p_usuario_id,
                jsonb_build_array(jsonb_build_object(
                    'produto_id', v_count.produto_id,
                    'deposito_id', v_session.deposito_id,
                    'tipo_movimentacao', 'BALANCO',
                    'quantidade', v_count.quantidade_contada,
                    'motivo', 'Ajuste via inventário ' || p_sessao_id::text
                              || CASE WHEN v_count.justificativa = '' THEN '' ELSE ': ' || v_count.justificativa END,
                    'expected_saldo', v_count.quantidade_sistema
                ))
            );
            v_applied := v_applied + 1;
        END IF;
    END LOOP;

    UPDATE public.sessoes_inventario
       SET status = 'FINALIZADA', finalizado_por = p_usuario_id,
           resultado = jsonb_build_object('status', 'success', 'sessao_id', p_sessao_id,
                                          'ajustes_realizados', v_applied),
           data_fim = now(), updated_at = now()
     WHERE id = p_sessao_id;

    RETURN (SELECT resultado FROM public.sessoes_inventario WHERE id = p_sessao_id);
END
$function$;

REVOKE ALL ON FUNCTION public.abrir_sessao_inventario(integer, integer, integer[], text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.registrar_contagem_inventario(uuid, integer, numeric, text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.finalizar_sessao_inventario(uuid, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.abrir_sessao_inventario(integer, integer, integer[], text) TO service_role;
GRANT EXECUTE ON FUNCTION public.registrar_contagem_inventario(uuid, integer, numeric, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.finalizar_sessao_inventario(uuid, integer) TO service_role;

COMMENT ON TABLE public.sessoes_inventario IS
    'Sessões de inventário físico com snapshot e fechamento transacional pelo ledger de estoque.';
