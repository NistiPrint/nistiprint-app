-- Padroniza e consolida miolos intermediarios importados.
-- A migracao e deliberadamente transacional: casos sem codigo unico ficam
-- preservados e registrados para revisao, enquanto os demais sao consolidados.

BEGIN;

CREATE TABLE IF NOT EXISTS public.produto_miolo_consolidacao_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL,
  source_id integer,
  canonical_id integer,
  codigo text,
  action text NOT NULL,
  resolution_method text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TEMP TABLE _miolo_direct_candidates ON COMMIT DROP AS
WITH source_items AS (
  SELECT p.id,
         x->>'item_id' AS item_id
  FROM public.produtos p
  CROSS JOIN LATERAL jsonb_array_elements(
    coalesce(p.atributos->'catalog_import_sources', '[]'::jsonb)
  ) x
  WHERE p.categoria_id = 6
    AND p.sku LIKE 'PI-IMP-%'
), candidates AS (
  SELECT DISTINCT s.id, left(pa.sku_externo, 6) AS codigo
  FROM source_items s
  JOIN public.produto_anuncios pa ON pa.item_externo_id = s.item_id
  WHERE pa.sku_externo ~ '^[A-Z0-9]{6}_'
)
SELECT id, array_agg(codigo ORDER BY codigo) AS codigos
FROM candidates
GROUP BY id;

CREATE TEMP TABLE _miolo_text_candidates ON COMMIT DROP AS
WITH imported AS (
  SELECT p.id,
         lower(regexp_replace(
           regexp_replace(p.nome, '^miolo\\s*[—-]?\\s*', '', 'i'),
           '[^a-z0-9]', '', 'g'
         )) AS nome_normalizado
  FROM public.produtos p
  WHERE p.categoria_id = 6
    AND p.sku LIKE 'PI-IMP-%'
), candidates AS (
  SELECT DISTINCT i.id, left(pa.sku_externo, 6) AS codigo
  FROM imported i
  JOIN public.produtos p
    ON p.categoria_id <> 6
   AND (
     i.nome_normalizado LIKE '%' || lower(regexp_replace(p.nome, '[^a-z0-9]', '', 'g')) || '%'
     OR lower(regexp_replace(p.nome, '[^a-z0-9]', '', 'g')) LIKE '%' || i.nome_normalizado || '%'
   )
  JOIN public.produto_anuncios pa ON pa.produto_id = p.id
  WHERE pa.sku_externo ~ '^[A-Z0-9]{6}_'
)
SELECT id, array_agg(codigo ORDER BY codigo) AS codigos
FROM candidates
GROUP BY id;

CREATE TEMP TABLE _miolo_resolution ON COMMIT DROP AS
WITH imported AS (
  SELECT p.id
  FROM public.produtos p
  WHERE p.categoria_id = 6 AND p.sku LIKE 'PI-IMP-%'
), resolved AS (
  SELECT i.id,
         d.codigos[1] AS codigo,
         'produto_anuncios'::text AS metodo
  FROM imported i
  JOIN _miolo_direct_candidates d ON d.id = i.id
  WHERE cardinality(d.codigos) = 1
  UNION ALL
  SELECT i.id,
         t.codigos[1] AS codigo,
         'correspondencia_nome'::text AS metodo
  FROM imported i
  LEFT JOIN _miolo_direct_candidates d ON d.id = i.id
  JOIN _miolo_text_candidates t ON t.id = i.id
  WHERE (d.id IS NULL OR cardinality(d.codigos) <> 1)
    AND cardinality(t.codigos) = 1
), canonical_ids AS (
  SELECT r.codigo,
         coalesce(min(existing.id), min(r.id)) AS canonical_id
  FROM resolved r
  LEFT JOIN public.produtos existing
    ON existing.categoria_id = 6
   AND existing.sku = 'MIOLO-' || r.codigo
  GROUP BY r.codigo
), canonical AS (
  SELECT r.id AS source_id, r.codigo, r.metodo, c.canonical_id
  FROM resolved r
  JOIN canonical_ids c ON c.codigo = r.codigo
)
SELECT * FROM canonical;

CREATE INDEX _miolo_resolution_source_idx ON _miolo_resolution(source_id);
CREATE INDEX _miolo_resolution_canonical_idx ON _miolo_resolution(canonical_id);
ANALYZE _miolo_resolution;

CREATE TEMP TABLE _miolo_unresolved ON COMMIT DROP AS
WITH imported AS (
  SELECT p.id,
         p.nome,
         coalesce(d.codigos, '{}'::text[]) AS direct_codes,
         coalesce(t.codigos, '{}'::text[]) AS text_codes
  FROM public.produtos p
  LEFT JOIN _miolo_direct_candidates d ON d.id = p.id
  LEFT JOIN _miolo_text_candidates t ON t.id = p.id
  WHERE p.categoria_id = 6 AND p.sku LIKE 'PI-IMP-%'
)
SELECT id, nome, direct_codes, text_codes,
       CASE
         WHEN cardinality(direct_codes) > 1 THEN 'vinculo_direto_ambiguo'
         WHEN cardinality(direct_codes) = 0 AND cardinality(text_codes) > 1 THEN 'nome_ambiguo'
         ELSE 'sem_codigo_unico'
       END AS motivo
FROM imported i
WHERE NOT EXISTS (SELECT 1 FROM _miolo_resolution r WHERE r.source_id = i.id);

DO $$
DECLARE
  v_run uuid := gen_random_uuid();
  v_fk record;
  v_has_rows boolean;
  v_conflict record;
BEGIN
  INSERT INTO public.produto_miolo_consolidacao_log
    (run_id, source_id, canonical_id, codigo, action, resolution_method, details)
  SELECT v_run, source_id, canonical_id, codigo, 'resolvido', metodo,
         jsonb_build_object('source_sku', p.sku, 'source_name', p.nome)
  FROM _miolo_resolution r
  JOIN public.produtos p ON p.id = r.source_id;

  INSERT INTO public.produto_miolo_consolidacao_log
    (run_id, source_id, action, details)
  SELECT v_run, id, 'pendente', jsonb_build_object(
    'nome', nome,
    'motivo', motivo,
    'direct_codes', direct_codes,
    'text_codes', text_codes
  )
  FROM _miolo_unresolved;

  -- Nunca sobrescrever outro SKU existente fora do conjunto que sera
  -- consolidado; um conflito aqui aborta a transacao inteira.
  IF EXISTS (
    SELECT 1
    FROM _miolo_resolution r
    JOIN public.produtos p ON p.id = r.canonical_id
    WHERE p.sku <> 'MIOLO-' || r.codigo
      AND NOT EXISTS (
        SELECT 1 FROM _miolo_resolution root
        WHERE root.source_id = root.canonical_id
          AND root.source_id = r.canonical_id
      )
  ) THEN
    RAISE EXCEPTION 'Conflito ao selecionar produto canonico de miolo';
  END IF;

  -- Atualiza toda FK simples que aponta para produtos.id. Isso cobre BOM,
  -- demandas, estoque, pedidos, vendas, artes, anuncios e tabelas futuras
  -- que mantenham o mesmo padrao de FK.
  FOR v_fk IN
    SELECT ns.nspname AS schema_name,
           nt.relname AS table_name,
           a.attname AS column_name
    FROM pg_constraint c
    JOIN pg_class nt ON nt.oid = c.conrelid
    JOIN pg_namespace ns ON ns.oid = nt.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
    WHERE c.contype = 'f'
      AND c.confrelid = 'public.produtos'::regclass
      AND cardinality(c.conkey) = 1
      AND cardinality(c.confkey) = 1
  LOOP
    EXECUTE format(
      'SELECT EXISTS (SELECT 1 FROM %I.%I target JOIN _miolo_resolution map
       ON target.%I = map.source_id WHERE map.source_id <> map.canonical_id)',
      v_fk.schema_name, v_fk.table_name, v_fk.column_name
    ) INTO v_has_rows;
    IF v_has_rows THEN
      EXECUTE format(
        'UPDATE %I.%I target SET %I = map.canonical_id
         FROM _miolo_resolution map
         WHERE target.%I = map.source_id
           AND map.source_id <> map.canonical_id',
        v_fk.schema_name, v_fk.table_name, v_fk.column_name,
        v_fk.column_name
      );
    END IF;
  END LOOP;

  -- Campos textuais derivados, que nao possuem FK.
  UPDATE public.ficha_tecnica f
  SET sku_componente = 'MIOLO-' || r.codigo
  FROM _miolo_resolution r
  WHERE f.componente_id = r.canonical_id;

  UPDATE public.itens_demanda i
  SET miolo_nome = 'Miolo ' || r.codigo,
      miolo_chave = r.codigo
  FROM _miolo_resolution r
  WHERE i.id_produto_miolo = r.canonical_id;

  -- Atualiza primeiro os registros canonicos. A chave unica de SKU fica
  -- protegida pelo preflight acima e a operacao ocorre dentro da transacao.
  UPDATE public.produtos p
  SET nome = 'Miolo ' || r.codigo,
      sku = 'MIOLO-' || r.codigo,
      updated_at = now()
  FROM _miolo_resolution r
  WHERE p.id = r.canonical_id;

  -- Remove somente duplicatas importadas que ja tiveram suas referencias
  -- apontadas para o canonico. Os seis casos pendentes permanecem intactos.
  DELETE FROM public.produtos p
  USING _miolo_resolution r
  WHERE p.id = r.source_id
    AND r.source_id <> r.canonical_id;

  -- Registra o resultado da limpeza por grupo canonico.
  INSERT INTO public.produto_miolo_consolidacao_log
    (run_id, canonical_id, codigo, action, details)
  SELECT v_run, canonical_id, codigo, 'consolidado',
         jsonb_build_object('sources', count(*), 'deleted', count(*) FILTER (WHERE source_id <> canonical_id))
  FROM _miolo_resolution
  GROUP BY canonical_id, codigo;
END $$;

-- Invariantes de seguranca: nenhum miolo convertido pode manter SKU antigo
-- ou duplicar o SKU canonico, e todas as referencias devem resolver.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.produtos
    WHERE categoria_id = 6 AND sku LIKE 'MIOLO-%'
    GROUP BY sku HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'SKU canonico de miolo duplicado';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.ficha_tecnica f
    JOIN public.produtos p ON p.id = f.componente_id
    WHERE p.categoria_id = 6 AND p.sku LIKE 'PI-IMP-%'
  ) THEN
    RAISE EXCEPTION 'Referencia de BOM aponta para miolo importado removivel';
  END IF;
END $$;

COMMIT;
