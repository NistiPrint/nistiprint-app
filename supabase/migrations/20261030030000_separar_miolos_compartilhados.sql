-- Corrige componentes legados que foram compartilhados por mais de um codigo.

BEGIN;

CREATE TABLE IF NOT EXISTS public.miolo_codigo_separacao_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL,
  codigo text NOT NULL,
  source_id integer,
  canonical_id integer,
  action text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TEMP TABLE _separacao_canonicos (
  codigo text PRIMARY KEY,
  source_id integer NOT NULL,
  canonical_id integer NOT NULL
) ON COMMIT DROP;

CREATE TEMP TABLE _separacao_codes ON COMMIT DROP AS
SELECT split_part(p.sku, '_', 1) AS codigo,
       min(ft.componente_id) AS source_id
FROM public.produtos p
JOIN public.ficha_tecnica ft ON ft.produto_pai_id = p.id
JOIN public.produtos m ON m.id = ft.componente_id AND m.categoria_id = 6
WHERE p.categoria_id IN (7, 11)
  AND p.formato <> 'kit'
  AND p.sku ~ '^[A-Z0-9]{4,6}(_|$)'
  AND length(split_part(p.sku, '_', 1)) IN (4, 6)
GROUP BY split_part(p.sku, '_', 1);

DO $$
DECLARE
  v record;
  v_existing integer;
  v_canonical integer;
  v_run uuid := gen_random_uuid();
BEGIN
  FOR v IN SELECT codigo, source_id FROM _separacao_codes ORDER BY codigo LOOP
    SELECT min(id) INTO v_existing
      FROM public.produtos
     WHERE categoria_id = 6 AND sku = 'MIOLO-' || v.codigo;

    IF v_existing IS NOT NULL THEN
      v_canonical := v_existing;
    ELSIF EXISTS (SELECT 1 FROM _separacao_canonicos WHERE canonical_id = v.source_id) THEN
      INSERT INTO public.produtos (
        nome, sku, descricao, categoria_id, tags, atributos, precificacao,
        dados_estoque, preco_custo, preco_venda, tipo_material,
        unidade_medida_id, status, estagio, formato, herdar_dados_pai, herdar_bom_pai
      )
      SELECT 'Miolo ' || v.codigo, 'MIOLO-' || v.codigo, descricao, 6, tags,
             atributos, precificacao, '{}'::jsonb, preco_custo, preco_venda,
             'intermediario', unidade_medida_id, status, estagio, 'simples', true, true
        FROM public.produtos WHERE id = v.source_id
      RETURNING id INTO v_canonical;
    ELSE
      v_canonical := v.source_id;
    END IF;

    INSERT INTO _separacao_canonicos(codigo, source_id, canonical_id)
    VALUES (v.codigo, v.source_id, v_canonical);

    UPDATE public.produtos
       SET nome = 'Miolo ' || v.codigo,
           sku = 'MIOLO-' || v.codigo,
           categoria_id = 6,
           tipo_material = 'intermediario',
           updated_at = now()
     WHERE id = v_canonical;

    INSERT INTO public.miolo_codigo_separacao_log
      (run_id, codigo, source_id, canonical_id, action)
    VALUES (v_run, v.codigo, v.source_id, v_canonical,
            CASE WHEN v_canonical = v.source_id THEN 'canonico_reaproveitado' ELSE 'canonico_criado' END);
  END LOOP;
END $$;

CREATE TEMP TABLE _separacao_bom ON COMMIT DROP AS
SELECT p.id AS produto_id,
       c.codigo,
       c.canonical_id,
       sum(ft.quantidade_necessaria) AS quantidade_total,
       coalesce(min(ft.id) FILTER (WHERE ft.componente_id = c.canonical_id), min(ft.id)) AS keep_id
FROM public.produtos p
JOIN _separacao_canonicos c ON c.codigo = split_part(p.sku, '_', 1)
JOIN public.ficha_tecnica ft ON ft.produto_pai_id = p.id
JOIN public.produtos m ON m.id = ft.componente_id AND m.categoria_id = 6
WHERE p.categoria_id IN (7, 11)
  AND p.formato <> 'kit'
GROUP BY p.id, c.codigo, c.canonical_id;

DO $$
DECLARE
  v record;
BEGIN
  FOR v IN SELECT * FROM _separacao_bom LOOP
    UPDATE public.ficha_tecnica
       SET componente_id = v.canonical_id,
           quantidade_necessaria = v.quantidade_total,
           sku_componente = 'MIOLO-' || v.codigo,
           updated_at = now()
     WHERE id = v.keep_id;

    DELETE FROM public.ficha_tecnica
     WHERE produto_pai_id = v.produto_id
       AND id <> v.keep_id
       AND componente_id IN (
         SELECT ft2.componente_id
           FROM public.ficha_tecnica ft2
           JOIN public.produtos m2 ON m2.id = ft2.componente_id AND m2.categoria_id = 6
          WHERE ft2.produto_pai_id = v.produto_id
       );
  END LOOP;
END $$;

-- Demandas ja carregam o codigo em miolo_chave; use-o para separar referencias
-- historicas quando o antigo componente era compartilhado.
UPDATE public.itens_demanda i
   SET id_produto_miolo = c.canonical_id,
       miolo_nome = c.codigo,
       miolo_chave = c.codigo
  FROM _separacao_canonicos c
 WHERE btrim(coalesce(i.miolo_chave, '')) = c.codigo;

COMMIT;
