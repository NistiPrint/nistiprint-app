BEGIN;
DO $$ DECLARE first jsonb; next_claim jsonb; ok boolean;
BEGIN
 first:=marketplace_pedidos_claim(6);
 IF first->>'status'='busy' THEN RAISE EXCEPTION 'initial claim busy'; END IF;
 IF (first->>'window_end')::timestamptz-(first->>'window_start')::timestamptz<>interval '90 days' THEN RAISE EXCEPTION 'initial scan must cover 90 days'; END IF;
 next_claim:=marketplace_pedidos_claim(6);
 IF next_claim->>'status'<>'busy' THEN RAISE EXCEPTION 'concurrent claim accepted'; END IF;
 ok:=marketplace_pedidos_finish(6,(first->>'owner_token')::uuid,'{"offset":10}',false,NULL);
 IF NOT ok THEN RAISE EXCEPTION 'checkpoint write failed'; END IF;
 next_claim:=marketplace_pedidos_claim(6);
 IF next_claim->'cursor'->>'offset'<>'10' THEN RAISE EXCEPTION 'checkpoint not resumed'; END IF;
 IF marketplace_pedidos_finish(6,(first->>'owner_token')::uuid,'{}',true,NULL) THEN RAISE EXCEPTION 'old worker accepted'; END IF;
 ok:=marketplace_pedidos_finish(6,(next_claim->>'owner_token')::uuid,'{}',true,NULL);
 IF NOT ok THEN RAISE EXCEPTION 'completion failed'; END IF;
 IF NOT (SELECT initial_scan_completed FROM marketplace_pedidos_coleta WHERE account_id=6) THEN RAISE EXCEPTION 'initial scan not recorded'; END IF;
 IF marketplace_pedidos_claim(6)->>'status'<>'busy' THEN RAISE EXCEPTION 'schedule ignored'; END IF;
 IF NOT marketplace_pedidos_backfill(6,90) THEN RAISE EXCEPTION 'backfill could not start'; END IF;
 next_claim:=marketplace_pedidos_claim(6);
 IF (next_claim->>'window_end')::timestamptz-(next_claim->>'window_start')::timestamptz<>interval '90 days' THEN RAISE EXCEPTION 'backfill window wrong'; END IF;
 IF marketplace_pedidos_backfill(6,90) THEN RAISE EXCEPTION 'backfill replaced active work'; END IF;
 ok:=marketplace_pedidos_finish(6,(next_claim->>'owner_token')::uuid,'{}',false,'rate_limited',900);
 IF NOT ok OR (SELECT next_attempt_at-now() FROM marketplace_pedidos_coleta WHERE account_id=6)<interval '15 minutes' THEN RAISE EXCEPTION 'retry-after ignored'; END IF;
 ok:=marketplace_pedidos_backfill_operacao(6,'11111111-1111-1111-1111-111111111111',90);
 IF NOT ok THEN RAISE EXCEPTION 'durable operation not created'; END IF;
 next_claim:=marketplace_pedidos_claim(6);
 IF next_claim->>'operation_id'<>'11111111-1111-1111-1111-111111111111' THEN RAISE EXCEPTION 'operation not resumed'; END IF;
 ok:=marketplace_pedidos_finish(6,(next_claim->>'owner_token')::uuid,'{}',false,'rate_limited',900);
 ok:=marketplace_pedidos_historico_operacao(6,'22222222-2222-2222-2222-222222222222','2025-01-01 03:00:00+00');
 IF NOT ok THEN RAISE EXCEPTION 'history could not start'; END IF;
 next_claim:=marketplace_pedidos_claim(6);
 IF next_claim->>'search_field'<>'created' OR (next_claim->>'window_start')::timestamptz<>'2025-01-01 03:00:00+00'::timestamptz THEN RAISE EXCEPTION 'history search parameters wrong'; END IF;
 IF marketplace_pedidos_historico_operacao(6,'22222222-2222-2222-2222-222222222222','2025-01-01 03:00:00+00') THEN RAISE EXCEPTION 'active history replaced'; END IF;
 UPDATE marketplace_pedidos_coleta SET window_end=now()-interval '10 days' WHERE account_id=6;
 ok:=marketplace_pedidos_finish(6,(next_claim->>'owner_token')::uuid,'{}',true,NULL);
 UPDATE marketplace_pedidos_coleta SET next_attempt_at=now() WHERE account_id=6;
 next_claim:=marketplace_pedidos_claim(6);
 IF next_claim->>'search_field'<>'updated' OR (next_claim->>'window_start')::timestamptz>now()-interval '10 days' THEN RAISE EXCEPTION 'incremental catchup left a gap'; END IF;
END $$;
ROLLBACK;
